// Raw-decode smoke KAT: exercise all required SHA-256 NI opcodes with
// distinguishable lane values.  Native x86 output is the reference.
.intel_syntax noprefix
.global _start
.section .text
_start:
    movdqu xmm0, XMMWORD PTR [rip + x0]
    movdqu xmm1, XMMWORD PTR [rip + x1]
    movdqu xmm2, XMMWORD PTR [rip + x2]
    sha256msg1 xmm1, xmm2
    sha256msg2 xmm1, xmm2
    sha256rnds2 xmm1, xmm2
    movdqu XMMWORD PTR [rip + out], xmm1
    mov eax, 1
    mov edi, 1
    lea rsi, [rip + out]
    mov edx, 16
    syscall
    mov eax, 60
    xor edi, edi
    syscall
.section .rodata
.align 16
x0: .byte 0x10,0x32,0x54,0x76,0x98,0xba,0xdc,0xfe,0x01,0x23,0x45,0x67,0x89,0xab,0xcd,0xef
x1: .byte 0x00,0x11,0x22,0x33,0x44,0x55,0x66,0x77,0x88,0x99,0xaa,0xbb,0xcc,0xdd,0xee,0xff
x2: .byte 0xde,0xad,0xbe,0xef,0xca,0xfe,0xba,0xbe,0x13,0x57,0x9b,0xdf,0x24,0x68,0xac,0xe0
.section .data
.align 16
out: .zero 16
