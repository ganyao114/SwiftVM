#!/usr/bin/env python3
"""Generate the single immutable ARM32 decoder and semantic field adapters."""
from pathlib import Path
import argparse
import json
import re

ROOT = Path(__file__).resolve().parents[2]
DEST = ROOT / 'source/runtime/frontend/arm32'
GROUPS = ('arm', 'thumb16', 'thumb32', 'vfp', 'neon')
FIRST_NEON = {'VBIC, VMOV, VMVN, VORR (immediate)', 'VEXT', 'VTBL', 'VTBX', 'VDUP (scalar)'}
LAST_NEON = {'VMLA (scalar)', 'VMLAL (scalar)', 'VQDMLAL/VQDMLSL (scalar)', 'VMUL (scalar)', 'VMULL (scalar)', 'VQDMULL (scalar)', 'VQDMULH (scalar)', 'VQRDMULH (scalar)'}
NOTICE = '// Generated by tools/arm32/generate_decode.py; do not edit.\n// Encoding definitions adapted from Dynarmic A32; see decode/NOTICE.\n// SPDX-License-Identifier: 0BSD\n'

def write(path, content):
    # Generated includes can be read by an active incremental compiler.
    # Keep unchanged files and publish changed files as complete snapshots.
    if path.exists() and path.read_text() == content:
        return
    temporary = path.with_suffix(path.suffix + '.tmp')
    temporary.write_text(content)
    temporary.replace(path)

def parse_patterns(group):
    rows = []
    for line in (DEST / 'decode' / (group + '.inc')).read_text().splitlines():
        m = re.match(r'\s*INST\((\w+),\s*"([^"]*)"\s*,\s*"([^"]*)"', line)
        if not m:
            continue
        name, label, bits = m.groups()
        mask = expected = 0
        fields = []
        previous = ''
        for i, char in enumerate(bits):
            bit = len(bits) - i - 1
            if char in '01':
                mask |= 1 << bit
                if char == '1':
                    expected |= 1 << bit
            if char in '01-':
                previous = ''
                continue
            if char != previous:
                fields.append([char, 0, bit])
                previous = char
            fields[-1][1] |= 1 << bit
            fields[-1][2] = bit
        rows.append(dict(name=name, label=label, bits=bits, mask=mask, expected=expected,
                         fields=fields, group=group))
    if group == 'arm':
        rows.sort(key=lambda x: -x['mask'].bit_count())
    if group == 'neon':
        rows.sort(key=lambda x: (0 if x['label'] in FIRST_NEON else 2 if x['label'] in LAST_NEON else 1,
                                 0 if x['label'] in FIRST_NEON | LAST_NEON else -x['mask'].bit_count()))
    if group == 'vfp':
        rows = [x for x in rows if x['mask'] & 0xf0000000 == 0xf0000000] + [x for x in rows if x['mask'] & 0xf0000000 != 0xf0000000]
    return rows

def extraction(field):
    _, mask, shift = field
    return f'((word & 0x{mask:08x}u) >> {shift})'

def import_reference(reference):
    decoder = reference / 'src/dynarmic/frontend/A32/decoder'
    for group in GROUPS:
        source = decoder / ('asimd.inc' if group == 'neon' else group + '.inc')
        (DEST / 'decode' / (group + '.inc')).write_text(source.read_text())
    header = (reference / 'src/dynarmic/frontend/A32/translate/impl/a32_translate_impl.h').read_text()
    methods = {}
    for m in re.finditer(r'bool\s+(\w+)\s*\(([^;{}]*)\)\s*(?:;|\{)', header):
        parameters = []
        for param in m.group(2).split(','):
            param = param.strip()
            if not param:
                continue
            kind, name = param.rsplit(' ', 1) if ' ' in param else (param, f'argument_{len(parameters)}')
            parameters.append([kind.strip(), name])
        methods[m.group(1)] = parameters
    (DEST / 'decode/signatures.json').write_text(json.dumps(methods, indent=2) + '\n')
    (DEST / 'decode/NOTICE').write_text('''Encoding definitions and field signatures are adapted from Dynarmic A32.
Reference: https://github.com/ganyao114/dynarmic-interp
Revision: 5a76f6930935bc07a2aa5158f3ee515c34ca14fd
Copyright (c) 2016-2020 MerryMage and original contributors.
SPDX-License-Identifier: 0BSD
Original decoder tables credit Lioncash. Original notices remain in imported files.
The decoder and dispatch generation here has no Dynarmic runtime dependency.
''')
    (DEST / 'decode/LICENSE.txt').write_text((reference / 'LICENSE.txt').read_text())

def run():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--import-reference', type=Path)
    args = parser.parse_args()
    if args.import_reference:
        import_reference(args.import_reference)
    groups = {g: parse_patterns(g) for g in GROUPS}
    methods = json.loads((DEST / 'decode/signatures.json').read_text())
    ordered = []
    unique = {}
    for group in GROUPS:
        for row in groups[group]:
            name = row['name']
            if name not in unique:
                ordered.append(name)
                unique[name] = row
            else:
                assert unique[name]['fields'] == row['fields'], name
            assert name in methods, name
            assert len(methods[name]) == len(row['fields']), (name, methods[name], row['fields'])
    write(DEST / 'opcodes.inc', NOTICE + ''.join(f'ARM32_OPCODE({n})\n' for n in ordered))
    dispatch = [NOTICE]
    for name in ordered:
        row = unique[name]
        values = ', '.join(f'static_cast<{kind}>({extraction(field)})'
                           for (kind, _), field in zip(methods[name], row['fields']))
        dispatch += [f'bool HandleDecoded_{name}(u32 word) {{\n',
                     f'    return {name}({values});\n', '}\n\n']
    dispatch += ['bool Dispatch(const Instruction& instruction) {\n',
                 '    using Handler = bool (Semantics::*)(u32);\n',
                 '    static constexpr Handler handlers[]{\n',
                 '        &Semantics::HandleDecodedUndefined,\n']
    dispatch += [f'        &Semantics::HandleDecoded_{name},\n' for name in ordered]
    dispatch += ['    };\n',
                 '    return (this->*handlers[instruction.OpcodeCode()])(instruction.SemanticWord());\n',
                 '}\n\n',
                 'bool HandleDecodedUndefined(u32) { return UndefinedInstruction(); }\n']
    write(DEST / 'decode/generated_dispatch.inc', ''.join(dispatch))

    pattern_lines = []
    buckets = {}
    selected = {}
    ids = {name: i + 1 for i, name in enumerate(ordered)}
    # The public tables retain references by compact pattern indices. VFP
    # conditional entries are never admitted for the unconditional ARM space.
    for group in GROUPS:
        selected[group] = []
        for row in groups[group]:
            row['id'] = len(pattern_lines)
            vfp_cond = group == 'vfp' and row['mask'] & 0xf0000000 != 0xf0000000
            pattern_lines.append(f'    {{0x{row["mask"]:08x}u, 0x{row["expected"]:08x}u, Opcode::{row["name"]}, Group::{ {"arm":"Arm","thumb16":"Thumb16","thumb32":"Thumb32","vfp":"VFP","neon":"NEON"}[group] }, {str(vfp_cond).lower()}}},\n')
            selected[group].append(row)
    combined = selected['vfp'] + selected['neon'] + selected['arm']
    index = lambda word: ((word >> 4) & 15) | ((word >> 16) & 0xff0)
    candidate_rows = []
    arm_buckets = []
    # Deduplicate identical buckets; this reduces the static candidate arena
    # without any startup allocation or visitor-specific copy.
    for key in range(4096):
        entries = tuple(row['id'] for row in combined if key & index(row['mask']) == index(row['expected']))
        if entries not in buckets:
            buckets[entries] = len(candidate_rows)
            candidate_rows.extend(entries)
        arm_buckets.append((buckets[entries], len(entries)))
    thumb16 = []
    for word in range(65536):
        hit = next((row for row in selected['thumb16'] if word & row['mask'] == row['expected']), None)
        thumb16.append(ids[hit['name']] if hit else 0)
    # Thumb32 lookup includes VFP and normalized NEON through the same ARM
    # candidate list, then the ordered Thumb32 table. Core Thumb32 high-byte
    # buckets keep the candidate arena small.
    thumb_rows = []
    thumb_buckets = []
    seen_thumb = {}
    for key in range(256):
        entries = tuple(row['id'] for row in selected['thumb32'] if key & (row['mask'] >> 24) == row['expected'] >> 24)
        if entries not in seen_thumb:
            seen_thumb[entries] = len(thumb_rows)
            thumb_rows.extend(entries)
        thumb_buckets.append((seen_thumb[entries], len(entries)))
    def array(values, width=16):
        return ''.join('    ' + ', '.join(str(v) for v in values[i:i+width]) + ',\n' for i in range(0, len(values), width))
    output = [NOTICE, 'constexpr Pattern patterns[]{\n', *pattern_lines, '};\n\n',
              'constexpr Bucket arm_buckets[]{\n', *[f'    {{{start}, {count}}},\n' for start,count in arm_buckets], '};\n',
              'constexpr std::uint16_t arm_candidates[]{\n',array(candidate_rows),'};\n\n',
              'constexpr std::uint16_t thumb16_opcodes[]{\n',array(thumb16),'};\n\n',
              'constexpr Bucket thumb32_buckets[]{\n',*[f'    {{{start}, {count}}},\n' for start,count in thumb_buckets],'};\n',
              'constexpr std::uint16_t thumb32_candidates[]{\n',array(thumb_rows),'};\n\n']
    write(DEST / 'decode/generated_tables.inc', ''.join(output).rstrip() + '\n')
    # Metadata supplies only the encoding facts needed before semantics. The
    # declaration names recover destination/list fields without decoding twice.
    metadata = [NOTICE, 'constexpr OpcodeInfo opcode_info[]{\n', '    {"Undefined", Group::Arm, FlowEncoding::None, 0, 0, 0, false, true},\n']
    for name in ordered:
        row = unique[name]
        fields = {pname: field for (_, pname), field in zip(methods[name], row['fields'])}
        group = {'arm':'Arm','thumb16':'Thumb16','thumb32':'Thumb32','vfp':'VFP','neon':'NEON'}[row['group']]
        flow = {
            'arm_B':'ArmB', 'arm_BL':'ArmBL', 'arm_BLX_imm':'ArmBLX',
            'arm_BX':'Indirect', 'arm_BXJ':'Indirect', 'arm_BLX_reg':'IndirectCall',
            'thumb16_B_t2':'ThumbB', 'thumb16_B_t1':'ThumbBCond',
            'thumb16_BLX_reg':'IndirectCall', 'thumb16_BX':'Indirect',
            'thumb16_CBZ_CBNZ':'ThumbCBZ',
            'thumb32_B':'ThumbWideB', 'thumb32_B_cond':'ThumbWideBCond',
            'thumb32_BL_imm':'ThumbBL', 'thumb32_BLX_imm':'ThumbBLX',
            'thumb32_TBB':'Indirect', 'thumb32_TBH':'Indirect', 'thumb32_BXJ':'Indirect',
        }.get(name,'None')
        destination = fields.get('d')
        if not destination and ('LDR' in name or name == 'thumb16_MOV_reg'):
            destination = fields.get('t')
        reg_mask,reg_shift = (destination[1],destination[2]) if destination and destination[1].bit_count()==4 else (0,0)
        list_mask = 0
        if 'LDM' in name or name in ('thumb32_POP','thumb16_POP'):
            for (kind,pname),field in zip(methods[name],row['fields']):
                if pname=='reg_list' and field[1].bit_count() >= 16: list_mask=field[1] & (1 << (field[2]+15))
            if name=='thumb16_POP': list_mask=1 << 8
        conditional = any(candidate['group'] in ('arm', 'vfp') and
                          candidate['mask'] & 0xf0000000 == 0
                          for group_rows in groups.values() for candidate in group_rows
                          if candidate['name'] == name)
        service = any(s in name for s in ('_SVC','_BKPT','_HLT','_UDF'))
        boundary = service or name in ('thumb16_IT','vfp_VMSR','arm_ISB','thumb32_ISB') or any(s in name for s in ('LDREX','STREX','CLREX','LDAEX','STLEX','_MSR','_MCR','_MRC','_CDP','_SETEND','_CPS','_RFE','_SRS','_eret','_usr'))
        metadata.append(f'    {{"{name}", Group::{group}, FlowEncoding::{flow}, 0x{reg_mask:08x}u, {reg_shift}, 0x{list_mask:08x}u, {str(conditional).lower()}, {str(boundary).lower()}}},\n')
    metadata.append('};\n')
    write(DEST / 'decode/generated_metadata.inc', ''.join(metadata))
    summary = {'patterns':sum(len(x) for x in groups.values()),'opcodes':len(ordered),
               'groups':{g:len(groups[g]) for g in GROUPS},'arm_candidate_rows':len(candidate_rows),
               'arm_unique_buckets':len(buckets),'arm_max_candidates':max(n for _,n in arm_buckets),
               'thumb32_candidate_rows':len(thumb_rows),'thumb16_table_bytes':len(thumb16)*2,
               'reference_revision':'5a76f6930935bc07a2aa5158f3ee515c34ca14fd'}
    write(DEST / 'decode/generated_statistics.json', json.dumps(summary,indent=2)+'\n')
    print(json.dumps(summary))

if __name__ == '__main__':
    run()
